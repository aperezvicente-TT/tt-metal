"""Phase composites from built kernel descriptors (Stage 14, the per-link lane cores of the sharded DSA phase; doc
ttnn/14-production-tp8-megakernel/dsa/shard_w16/levers_design.md section 6).

merge(phases, core) turns N SOURCE_CODE kernel descriptors of ONE RISC role (all writer / BRISC or all reader /
NCRISC) into one SOURCE_CODE kernel on `core` that runs them back to back, in the established composite form
(kernels/mk/root_dm0.cpp; kernels/mk/phase_args.hpp):

- every #include line of every phase is hoisted to global scope first (a header first seen inside a phase namespace
  would put its definitions into that namespace); inside the namespaces the same lines are no-ops (include guards);
- phase k sits in `namespace phk { constexpr uint32_t PH_CT0 = ...; uint32_t ph_rt0 = ...; #define ... #include-text
  #undef ... }` with its own defines (minus `drop`), its kernel_main renamed phase_main; its compile-time args start at
  PH_CT0 and its runtime args (this core's, including the fabric connections already appended) at ph_rt0 -- the phase
  kernels read theirs at those bases (fabric_stream/fs_send.cpp / fs_read.cpp, fabric_ar/lane_send.cpp / lane_recv.cpp);
- with fabric senders (packet_header_pool.h among the includes) PacketHeaderPool::reset() runs between phases: every
  phase drains and closes its connections before it returns, so the next one reuses the same header slots (one shared
  per-direction set instead of the sum of the phases' allocations).

A phase's text is used as is (its inlined common headers, e.g. fs_common.hpp, become phk::fs: one private copy per
phase, no shared state). MK_PROBE_ARG must not be among a phase's defines (probe.hpp's macros are fixed at its first,
global include): build the phases without their probe pair."""

from __future__ import annotations

import re

import ttnn
from models.autoports.zai_org_glm_5_3_flash.tt.mk_dense import _cores_of

_INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]*[<"][^>"]+[>"].*$', re.M)


def _cores(kd) -> set:
    return {(int(x), int(y)) for x, y in _cores_of(kd.core_ranges)}


def phase_rt(kd, core) -> list:
    """the runtime args of kernel descriptor `kd` on `core` (a list; [] when it has none there)"""
    if (int(core[0]), int(core[1])) not in _cores(kd):
        return []
    return list(kd.runtime_args[int(core[0])][int(core[1])])


def merge(phases: list, core: tuple, *, name: str = "composite") -> "ttnn.KernelDescriptor":
    """phases = [(kernel descriptor, drop: set of define names)] in run order, every one SOURCE_CODE and with `core`
    among its cores, all of one config kind -> one KernelDescriptor on `core` (its runtime args = the phases' runtime
    args on `core`, concatenated)."""
    assert phases, "merge: no phases"
    core = (int(core[0]), int(core[1]))
    kinds = {type(kd.config).__name__ for kd, _ in phases}
    assert len(kinds) == 1, ("merge: one RISC role per composite", kinds)
    hoist, bodies, ct, rt = [], [], [], []
    for k, (kd, drop) in enumerate(phases):
        assert kd.source_type == ttnn.KernelDescriptor.SourceType.SOURCE_CODE, (name, k, "SOURCE_CODE phases only")
        assert core in _cores(kd), (name, k, core, "the phase does not run on this core")
        defs = [(str(a), str(b)) for a, b in kd.defines if str(a) not in (drop or ())]
        assert all(a != "MK_PROBE_ARG" for a, _ in defs), (name, k, "build composite phases without the probe pair")
        text = str(kd.kernel_source)
        for m in _INCLUDE.finditer(text):
            line = m.group(0).strip()
            if line not in hoist:
                hoist.append(line)
        body = [f"namespace ph{k} {{", f"constexpr uint32_t PH_CT0 = {len(ct)};", f"uint32_t ph_rt0 = {len(rt)};"]
        body += [f"#define {a} {b}" for a, b in defs]
        body += ["#define kernel_main phase_main", text, "#undef kernel_main"]
        body += [f"#undef {a}" for a, _ in defs]
        body.append(f"}}  // namespace ph{k}")
        bodies.append("\n".join(body))
        ct += [int(v) for v in kd.compile_time_args]
        rt += phase_rt(kd, core)
    fabric = any("packet_header_pool.h" in h for h in hoist)
    calls = []
    for k in range(len(phases)):
        if k > 0 and fabric:
            calls.append("    PacketHeaderPool::reset();  // the previous phase drained and closed its connections")
        calls.append(f"    ph{k}::phase_main();")
    src = "\n".join(
        [f"// {name}: generated by tt/phase_merge.py ({len(phases)} phases)", "#define MK_PHASED 1", "#include <cstdint>",
         "#include <cstddef>"]
        + hoist
        + bodies
        + ["void kernel_main() {"] + calls + ["}", ""]
    )
    rta = ttnn.RuntimeArgs()
    rta[core[0]][core[1]] = rt
    kd0 = phases[0][0]
    return ttnn.KernelDescriptor(kernel_source=src, source_type=ttnn.KernelDescriptor.SourceType.SOURCE_CODE,
                                 core_ranges=ttnn.CoreRangeSet([ttnn.CoreRange(ttnn.CoreCoord(*core),
                                                                               ttnn.CoreCoord(*core))]),
                                 compile_time_args=ct, runtime_args=rta, config=kd0.config, defines=[])  # fmt: skip


def restrict(kd, keep: set):
    """kd with its runtime args on the cores of `keep` dropped from it (the cores now served by composites): a copy on
    the remaining cores, or None when none remain"""
    rest = sorted(_cores(kd) - set(keep))
    if not rest:
        return None
    rta = ttnn.RuntimeArgs()
    for x, y in rest:
        rta[x][y] = phase_rt(kd, (x, y))
    crs = ttnn.CoreRangeSet([ttnn.CoreRange(ttnn.CoreCoord(x, y), ttnn.CoreCoord(x, y)) for x, y in rest])
    return ttnn.KernelDescriptor(kernel_source=kd.kernel_source, source_type=kd.source_type, core_ranges=crs,
                                 compile_time_args=list(kd.compile_time_args), runtime_args=rta, config=kd.config,
                                 defines=list(kd.defines))  # fmt: skip
